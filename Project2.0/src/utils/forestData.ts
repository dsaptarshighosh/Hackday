const FORESTS_STORAGE_KEY = 'living_lens_monitored_forests';

export function loadStoredForests(): Forest[] {
  try {
    const raw = localStorage.getItem(FORESTS_STORAGE_KEY);
    if (!raw) {
      localStorage.setItem(FORESTS_STORAGE_KEY, JSON.stringify(INITIAL_DEMO_FORESTS));
      return INITIAL_DEMO_FORESTS;
    }
    const parsed = JSON.parse(raw);
    if (Array.isArray(parsed) && parsed.length > 0) {
      return parsed;
    }
  } catch (e) {
    console.error('Failed to load forests from localStorage', e);
  }
  return INITIAL_DEMO_FORESTS;
}

export function saveForests(forests: Forest[]): void {
  try {
    localStorage.setItem(FORESTS_STORAGE_KEY, JSON.stringify(forests));
  } catch (e) {
    console.error('Failed to save forests to localStorage', e);
  }
}
